#!/usr/bin/env python3
"""Regenerates src/content/generated.ts: static require() calls for every
organization.json / event.json and the image files they point at.
Metro (React Native) cannot scan folders at runtime, so run this after adding or
removing content:   python3 tools/build_content_index.py
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'content')
ORGS = os.path.join(ROOT, 'organizations')
IMAGE_FIELDS = ('logo', 'image', 'poster')


def rel(p):
    return './' + os.path.relpath(p, ROOT).replace(os.sep, '/')


def entry(json_path):
    folder = os.path.dirname(json_path)
    data = json.load(open(json_path, encoding='utf-8'))
    assets = []
    for f in IMAGE_FIELDS:
        v = data.get(f)
        if isinstance(v, str) and v:
            target = os.path.normpath(os.path.join(folder, v))
            if not os.path.isfile(target):
                sys.exit(f'{json_path}: "{f}" points to a missing file: {v}')
            assets.append(f"{f}: require('{rel(target)}')")
    return (f"  {{ path: '{rel(json_path)}', data: require('{rel(json_path)}'), "
            f"assets: {{ {', '.join(assets)} }} }},")


orgs, events = [], []
for dirpath, _, files in sorted(os.walk(ORGS)):
    for name in sorted(files):
        p = os.path.join(dirpath, name)
        if name == 'organization.json':
            orgs.append(entry(p))
        elif name == 'event.json':
            events.append(entry(p))

out = ['// AUTO-GENERATED by tools/build_content_index.py. Do not edit by hand.',
       '/* eslint-disable */',
       'export interface RawEntry { path: string; data: any; assets: Record<string, any> }',
       'export const ORGANIZATION_FILES: RawEntry[] = [', *orgs, '];',
       'export const EVENT_FILES: RawEntry[] = [', *events, '];', '']
open(os.path.join(ROOT, 'generated.ts'), 'w', encoding='utf-8').write('\n'.join(out))
print(f'generated.ts: {len(orgs)} organizations, {len(events)} events')
